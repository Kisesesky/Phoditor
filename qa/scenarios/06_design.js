// C: 쪽 이동 막대, [채우기] 메뉴, 표지 미리보기
try {
  await waitFor(() => $$('#companyGrid .company-card').length > 0);
  await waitFor(() => $$('#companyGrid .card-art img.cover-thumb').length >= 6, 4000);
  await shot('d01_start');
  await clickEl($$('#typeTabs button').find((b) => b.firstChild.textContent.trim() === '준공사진첩'), 200);
  await clickEl($$('#companyGrid .company-card').find((c) => c.querySelector('.company-name').textContent.trim() === '힐스테이트'), 1800);
  const tab = $$('#sheetTabsBar .sheet-tab').find((t) => t.querySelector('span').textContent === '84㎡A사진첩');
  await clickEl(tab, 700);
  for (let i = 0; i < 5; i++) await clickEl($('#addBlockEndBtn'), 300);
  const rail = () => $$('#pageRail .rail-item');
  check('쪽 이동 막대: 쪽마다 버튼(6쪽)', rail().length === $$('.pv-page').length && rail().length === 6, `${rail().length} / ${$$('.pv-page').length}`);
  check('블록 시트는 블록 번호도 표시', rail()[2].textContent.includes('#3'), rail()[2].textContent);
  rail()[4].click(); await sleep(900);
  const r5 = $$('.pv-page')[4].getBoundingClientRect();
  const vp = $('#gridViewport').getBoundingClientRect();
  check('누르면 그 쪽으로 이동하고 표시됨', Math.abs(r5.top - vp.top) < 120 && rail()[4].classList.contains('on'), `${Math.round(r5.top - vp.top)} ${rail().findIndex((b) => b.classList.contains('on'))}`);
  // [리본] 홈 · 사진 · 서식 · 보기 — 같은 일 하는 단추는 리본에 한 번만
  check('리본 탭 4개(홈·사진·서식·보기)', $$('#ribbonTabs button').map((b) => b.textContent).join() === '홈,사진,서식,보기');
  check('홈: 채우기 단추가 바로 보임(메뉴 없이)', !!$('.rb-panel.on #autoFillBtn') && !!$('.rb-panel.on #pasteTableBtn') && !$('#fillMenu'));
  await clickEl($('#pasteTableBtn'), 400);
  check('표 붙여넣기 창', !!$('.dyn-modal textarea'));
  $('.dyn-modal').remove();
  await clickEl($('#ribbonTabs [data-tab="photo"]'), 300);
  check('사진 탭: 자리를 안 고르면 꺼져 있고 안내', $('#rbCropBtn').disabled && !$('#rbPhotoHint').hidden);
  await shot('d02_ribbon_photo');
  await clickEl($('#ribbonTabs [data-tab="format"]'), 300);
  check('서식 탭: 칸을 안 고르면 꺼짐', $('#fmtBoldBtn').disabled && !$('#rbFormatHint').hidden);
  const cell = $$('.pv-page td.editable-cell').find((t) => t.textContent.trim() === '' && t.offsetWidth > 60);
  cell.click(); await sleep(300);
  const ed = cell.querySelector('.cell-editor-input');
  if (ed) ed.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  await sleep(300);
  check('칸을 고르면 서식 탭 켜짐(탭에 점 표시)', !$('#fmtBoldBtn').disabled && $('#ribbonTabs [data-tab="format"]').classList.contains('ctx-on'));
  const before = JSON.stringify(state.editor.sheets[state.activeSheetIdx].cellFonts || {});
  await clickEl($('#fmtBoldBtn'), 500);
  check('서식 > 굵게 적용', JSON.stringify(state.editor.sheets[state.activeSheetIdx].cellFonts || {}) !== before && $('#fmtBoldBtn').classList.contains('on'));
  await shot('d02b_ribbon_format');
  await clickEl($('#ribbonTabs [data-tab="view"]'), 300);
  await clickEl($('#rbSideBtn'), 500);
  check('보기 > 사진 패널 접기', $('#sidebar').classList.contains('collapsed') && !$('#rbSideBtn').classList.contains('on'));
  await clickEl($('#rbSideBtn'), 500);
  $('#ribbonTabs [data-tab="home"]').dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 2 })); await sleep(300);
  check('탭을 두 번 누르면 리본 접힘', $('#ribbon').classList.contains('collapsed'));
  await clickEl($('#ribbonTabs [data-tab="home"]'), 300);
  check('탭을 누르면 다시 펼침', !$('#ribbon').classList.contains('collapsed'));
  check('사진 위 단추·영역 위 배치 단추·사진 패널 크롭 단추 없음', !$('.slot-actions') && !$('.slot-remove-btn') && !$('.photo-area-toolbar') && !$$('#photoGrid .photo-item button').some((b) => b.textContent === '크롭'));
  await clickEl($$('#sheetTabsBar .sheet-tab')[0], 600);
  check('표지(1쪽)도 막대에 1', rail().length === 1);
  check('표지에서는 채우기 단추가 꺼짐', $('#autoFillBtn').disabled);
  await shot('d03_editor');
} catch (err) { check('예외 없음', false, String(err && err.stack || err)); }
return { checks, confirms };
